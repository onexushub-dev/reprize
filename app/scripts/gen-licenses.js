#!/usr/bin/env node
/**
 * Writes src/legal/thirdParty.ts: name, version, license and license text of every package in package.json's
 * "dependencies", read from node_modules. Shown in the app's hidden "Licenças de código aberto" screen
 * (src/app/licenses.tsx). Run again after adding or updating a dependency:
 *
 *     node scripts/gen-licenses.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const NAMES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'license.txt', 'LICENCE', 'LICENCE.md'];

function licenseName(p) {
  if (typeof p.license === 'string') return p.license;
  if (p.license && typeof p.license.type === 'string') return p.license.type;
  if (Array.isArray(p.licenses)) return p.licenses.map((l) => l.type).join(' OR ');
  return 'unknown';
}

const out = [];
for (const name of Object.keys(pkg.dependencies || {}).sort()) {
  const dir = path.join(root, 'node_modules', name);
  let p;
  try {
    p = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  } catch {
    console.warn(`skip ${name}: not installed`);
    continue;
  }
  let text = null;
  for (const f of NAMES) {
    const file = path.join(dir, f);
    if (fs.existsSync(file) && fs.statSync(file).isFile()) {
      text = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim();
      break;
    }
  }
  if (text === null) console.warn(`${name}: no license file, showing "${licenseName(p)}" only`);
  out.push({ name, version: p.version, license: licenseName(p), text });
}

const body =
  '// Generated by scripts/gen-licenses.js from package.json dependencies — do not edit by hand.\n' +
  'export type ThirdParty = { name: string; version: string; license: string; text: string | null };\n\n' +
  `export const THIRD_PARTY: ThirdParty[] = ${JSON.stringify(out, null, 2)};\n`;
fs.mkdirSync(path.join(root, 'src', 'legal'), { recursive: true });
fs.writeFileSync(path.join(root, 'src', 'legal', 'thirdParty.ts'), body);
console.log(`src/legal/thirdParty.ts: ${out.length} packages`);
